#!/bin/sh
# ============================================================
#  tsvpn-install.sh — install or update the tsvpn system on THIS
#  router. Runs ON the router.
#
#    sh tsvpn-install.sh <node.json>
#
#  Typical use: copy this whole scripts/ folder plus the one JSON
#  file for this router onto the box, then run it.
#
#      scp scripts/* my-remote.json root@192.168.8.1:/tmp/tsvpn/
#      ssh root@192.168.8.1 'sh /tmp/tsvpn/tsvpn-install.sh /tmp/tsvpn/my-remote.json'
#
#  Or let tsvpn-push.sh do both steps from your own machine.
#
#  What it does:
#    1. copies the generic scripts to /etc/tsvpn/
#    2. installs <node.json> as /etc/tsvpn/node.json
#    3. generates /etc/rc.local — a bootstrap carrying a copy of
#       all of it, so a firmware update cannot leave this router
#       unrepairable with nobody on site
#    4. lists /etc/tsvpn in /etc/sysupgrade.conf
#    5. runs the self-heal (scripts/glinet/README.md section 5), then the audit
#
#  Idempotent. Re-run it any time, including to change settings.
#  Needs the router already authenticated to the tailnet — see
#  the platform README (scripts/glinet/README.md section 2).
# ============================================================
set -e

SRC=$(cd "$(dirname "$0")" && pwd)
NODEJSON=$1
SCRIPTS="tsvpn-lib.sh tsvpn-selfheal.sh tsvpn-audit.sh tsvpn-fix-route.sh tsvpn-clone-mac.sh tsvpn-persist.sh"

if [ -z "$NODEJSON" ]; then
	if [ -f /etc/tsvpn/node.json ]; then
		NODEJSON=/etc/tsvpn/node.json
		echo "no node.json given — reusing the installed /etc/tsvpn/node.json"
	else
		sed -n '2,26p' "$0" | sed 's/^#\{1,2\} \{0,1\}//'
		exit 2
	fi
fi
[ -f "$NODEJSON" ] || { echo "no such file: $NODEJSON" >&2; exit 1; }

# ---------- 1. validate the node file ----------
command -v jsonfilter >/dev/null 2>&1 || { echo "jsonfilter not found — is this a GL.iNet/OpenWrt router?" >&2; exit 1; }

ROLE=$(jsonfilter -i "$NODEJSON" -e '@.role' 2>/dev/null || true)
case "$ROLE" in
	host|remote) ;;
	*) echo "\"role\" must be \"host\" or \"remote\", got \"${ROLE:-<missing>}\"" >&2; exit 1 ;;
esac
EXIT_NODE=$(jsonfilter -i "$NODEJSON" -e '@.exit_node' 2>/dev/null || true)
TARGETS=$(jsonfilter -i "$NODEJSON" -e '@.targets[*]' 2>/dev/null | tr '\n' ' ')
if [ "$ROLE" = "remote" ] && [ -z "$EXIT_NODE" ]; then
	echo "role=remote needs \"exit_node\": the host router's 100.x address." >&2; exit 1
fi
if [ "$ROLE" = "host" ] && [ -n "$EXIT_NODE" ]; then
	echo "role=host must not set \"exit_node\"." >&2; exit 1
fi
for t in $TARGETS; do
	case "$t" in
		*/*|*:*) echo "target \"$t\" must be a bare IPv4 address — no /32, no port." >&2; exit 1 ;;
	esac
done
echo "node.json valid: $(jsonfilter -i "$NODEJSON" -e '@.node' 2>/dev/null) role=$ROLE targets=${TARGETS:-<none>}"

# ---------- 2. install scripts + node.json ----------
mkdir -p /etc/tsvpn /var/log
for s in $SCRIPTS; do
	if [ -f "$SRC/$s" ]; then
		cat "$SRC/$s" > "/etc/tsvpn/$s"
	elif [ -f "/etc/tsvpn/$s" ]; then
		:   # already installed and not being replaced
	else
		echo "missing $s — copy the whole scripts/ folder across, not just the installer" >&2
		exit 1
	fi
done
[ "$NODEJSON" = "/etc/tsvpn/node.json" ] || cat "$NODEJSON" > /etc/tsvpn/node.json
chmod +x /etc/tsvpn/*.sh

# ---------- 3. generate rc.local ----------
TMPRC=/tmp/tsvpn-rc.$$
{
cat <<'HEAD'
# Put your custom commands here that should be executed once
# the system init finished. By default this file does nothing.

# GL.iNet firmware keeps /etc on a read-only-by-default UBIFS overlay.
# Guarded so this same rc.local also works on plain OpenWrt.
[ -f /lib/functions/gl_util.sh ] && { . /lib/functions/gl_util.sh; remount_ubifs; }

# === TSVPN-BOOTSTRAP =========================================
# GENERATED by tsvpn-install.sh — do not hand-edit.
# To change this router's settings: edit /etc/tsvpn/node.json and
# run /etc/tsvpn/tsvpn-persist.sh, or re-run the installer.
#
# WHY THE SCRIPTS ARE EMBEDDED HERE:
# A GL.iNet firmware update destroys /root and /etc/hotplug.d/iface,
# and is not guaranteed to honour /etc/sysupgrade.conf. It does
# preserve /etc/rc.local. So rc.local carries a full copy of
# /etc/tsvpn and rewrites it on every boot. That is what makes an
# unattended firmware update recoverable with nobody on site.
#
# Never point rc.local at a script under /root: /root does not
# survive a flash, so the boot log fills with "not found" while
# nothing is actually repaired.
mkdir -p /etc/tsvpn /var/log
HEAD

emit() {   # emit <dest-path> <marker> <source-file>
	printf '\ncat > %s <<%s%s%s\n' "$1" "'" "$2" "'"
	cat "$3"
	printf '%s\n' "$2"
}

emit /etc/tsvpn/node.json __TSVPN_NODE__ /etc/tsvpn/node.json
for s in $SCRIPTS; do
	emit "/etc/tsvpn/$s" "__TSVPN_$(echo "$s" | tr 'a-z.-' 'A-Z__')__" "/etc/tsvpn/$s"
done

cat <<'TAIL'

chmod +x /etc/tsvpn/*.sh

# Delayed: the self-heal waits for tailscaled itself, but starting late keeps
# the boot log clean and lets the network settle first.
( sleep 30; /etc/tsvpn/tsvpn-selfheal.sh > /var/log/tsvpn-selfheal.log 2>&1 ) &
# === END TSVPN-BOOTSTRAP =====================================

exit 0
TAIL
} > "$TMPRC"

# A payload containing its own terminator would silently truncate rc.local.
for s in $SCRIPTS; do
	m="__TSVPN_$(echo "$s" | tr 'a-z.-' 'A-Z__')__"
	grep -qx "$m" "/etc/tsvpn/$s" && { echo "FATAL: $s contains its own heredoc marker $m" >&2; rm -f "$TMPRC"; exit 1; }
done
grep -qx "__TSVPN_NODE__" /etc/tsvpn/node.json && { echo "FATAL: node.json contains the marker line" >&2; rm -f "$TMPRC"; exit 1; }

sh -n "$TMPRC" || { echo "generated rc.local failed the syntax check — not installing" >&2; rm -f "$TMPRC"; exit 1; }
grep -q "END TSVPN-BOOTSTRAP" "$TMPRC" || { echo "bootstrap end marker missing" >&2; rm -f "$TMPRC"; exit 1; }

[ -f /etc/rc.local ] && cp /etc/rc.local /etc/rc.local.bak-tsvpn
cat "$TMPRC" > /etc/rc.local
chmod +x /etc/rc.local
rm -f "$TMPRC"
echo "rc.local installed ($(wc -l < /etc/rc.local) lines); previous kept as /etc/rc.local.bak-tsvpn"

# ---------- 4. keep /etc/tsvpn across a sysupgrade too, where honoured ----------
touch /etc/sysupgrade.conf
grep -q "^/etc/tsvpn/" /etc/sysupgrade.conf || echo "/etc/tsvpn/" >> /etc/sysupgrade.conf
# retire the older /root layout: never call a path a flash deletes
sed -i "/root\/restore-tailscale.sh/d;/root\/fix-target-route.sh/d;/root\/clone-mac.sh/d" /etc/sysupgrade.conf 2>/dev/null || true

# ---------- 5. apply + verify ----------
echo
echo "running the self-heal (applies scripts/glinet/README.md section 5) ..."
/etc/tsvpn/tsvpn-selfheal.sh
