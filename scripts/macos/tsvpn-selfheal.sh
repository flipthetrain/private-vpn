#!/bin/sh
# ============================================================
#  tsvpn-selfheal.sh — rebuild this Mac's VPN configuration.
#
#  Runs at every boot from the com.tsvpn.selfheal LaunchDaemon,
#  and may be run by hand at any time. Idempotent.
#
#  This is also the PROVISIONER: configuring a Mac host is
#  nothing more than writing node.json and running this.
#
#  HOST ROLE ONLY - see tsvpn-lib.sh.
#
#  WHY IT EXISTS: nothing wipes configuration on macOS, but
#  net.inet.ip.forwarding does not survive a reboot, a system
#  update rewrites /etc/pf.conf, and a `tailscale up` typed
#  without the flags clears the advertisements. All three are
#  silent, and leave the Mac looking healthy in the console
#  while the tunnel carries nothing.
#
#  Generic. All values come from /etc/tsvpn/node.json.
# ============================================================
. "${TSVPN_DIR:-/etc/tsvpn}/tsvpn-lib.sh"
tsvpn_load || exit 1
tsvpn_check || exit 1

[ "$(id -u)" = "0" ] || { echo "run as root: sudo $0" >&2; exit 1; }

echo "== tsvpn self-heal: ${NODE:-$(hostname)} role=$ROLE $(date) =="
[ -n "$DEPLOYMENT" ] && echo "deployment: $DEPLOYMENT"
echo "macos     : $(sw_vers -productVersion 2>/dev/null) $(uname -m)"
echo "targets   : ${TARGETS:-<none>}"

TS=$(tsvpn_tailscale) || { echo "Tailscale not found. See README section 2." >&2; exit 1; }
if tsvpn_is_appstore_build; then
	echo "" >&2
	echo "This is the Mac App Store build of Tailscale." >&2
	echo "It is sandboxed and CANNOT advertise subnet routes or act as an exit" >&2
	echo "node, so it cannot be a host. Replace it with the standalone build:" >&2
	echo "    https://tailscale.com/download/mac  (choose the standalone .pkg)" >&2
	exit 1
fi

# --- wait for tailscaled ---
i=0
while [ $i -lt 60 ]; do
	"$TS" status >/dev/null 2>&1 && break
	sleep 5
	i=$((i + 1))
done
echo "tailscaled ready after $((i * 5))s"

# --- IP forwarding -----------------------------------------------------------
# A host forwards exit-node traffic and subnet-route traffic. macOS resets this
# on every boot, which is why the LaunchDaemon re-applies it rather than writing
# it somewhere once.
echo
echo "-- forwarding --"
sysctl -w net.inet.ip.forwarding=1 >/dev/null 2>&1 && echo "  net.inet.ip.forwarding = 1" \
	|| echo "  could not set net.inet.ip.forwarding" >&2
sysctl -w net.inet6.ip6.forwarding=1 >/dev/null 2>&1

# --- NAT for forwarded traffic ----------------------------------------------
# On Linux tailscaled installs this itself. On macOS it does not, so without it
# a target replies to a 100.x address it has no route to, and subnet routes
# silently fail while the exit node appears fine.
#
# Only forwarded traffic matches: this Mac's own packets leave en0 with en0's
# address, and its traffic to tailnet peers leaves on utun.
echo
echo "-- nat (pf) --"
EGRESS=$(route -n get default 2>/dev/null | awk '/interface:/{print $2; exit}')
if [ -z "$EGRESS" ]; then
	echo "  no default route interface found; skipping NAT" >&2
else
	echo "  egress interface: $EGRESS"
	mkdir -p /etc/pf.anchors
	cat > /etc/pf.anchors/tsvpn <<PFANCHOR
# Generated by tsvpn-selfheal.sh -- do not hand-edit; rewritten on every boot.
# SNAT traffic this Mac forwards on behalf of the tailnet, so replies come back.
nat on $EGRESS inet from 100.64.0.0/10 to any -> ($EGRESS)
PFANCHOR

	# pf only evaluates an anchor that the main ruleset declares. A macOS update
	# rewrites /etc/pf.conf and drops ours, so check and re-add every boot.
	if ! grep -q '^nat-anchor "tsvpn"' /etc/pf.conf 2>/dev/null; then
		[ -f /etc/pf.conf.tsvpn-backup ] || cp /etc/pf.conf /etc/pf.conf.tsvpn-backup
		awk '
			/^nat-anchor/ && !done { print; print "nat-anchor \"tsvpn\""; done=1; next }
			{ print }
			END { if (!done) print "nat-anchor \"tsvpn\"" }
		' /etc/pf.conf > /tmp/pf.conf.$$
		printf 'load anchor "tsvpn" from "/etc/pf.anchors/tsvpn"\n' >> /tmp/pf.conf.$$
		# Never install a ruleset that does not parse - that is how you lose the network.
		if pfctl -n -f /tmp/pf.conf.$$ >/dev/null 2>&1; then
			cat /tmp/pf.conf.$$ > /etc/pf.conf
			echo "  added the tsvpn anchor to /etc/pf.conf (backup: /etc/pf.conf.tsvpn-backup)"
		else
			echo "  generated pf.conf FAILED to parse; leaving /etc/pf.conf alone" >&2
		fi
		rm -f /tmp/pf.conf.$$
	fi

	if pfctl -n -f /etc/pf.conf >/dev/null 2>&1; then
		pfctl -f /etc/pf.conf >/dev/null 2>&1
		pfctl -e >/dev/null 2>&1   # already-enabled is not an error worth reporting
		echo "  pf ruleset loaded and enabled"
	else
		echo "  /etc/pf.conf does not parse; NOT loading it" >&2
	fi
fi

# --- DNS ---------------------------------------------------------------------
# macOS ships no DNS forwarder. That only matters if a REMOTE will forward its
# clients' lookups here; laptops and phones get DNS through the exit node.
echo
echo "-- dns --"
if [ -x /opt/homebrew/sbin/dnsmasq ] || [ -x /usr/local/sbin/dnsmasq ]; then
	echo "  dnsmasq is installed. See README section 5 to point a remote at it."
else
	echo "  no DNS forwarder on this Mac; nothing to configure."
	echo "  Fine for laptops and phones. For a REMOTE, see README section 5."
fi

# --- the control-plane settings, which anything can quietly reset -------------
echo
echo "-- advertisements --"
if [ -n "$ROUTES" ]; then
	"$TS" set --advertise-exit-node --advertise-routes="$ROUTES"
else
	"$TS" set --advertise-exit-node --advertise-routes=
fi

echo
echo "-- verify --"
sleep 3
"${TSVPN_DIR:-/etc/tsvpn}/tsvpn-audit.sh"
rc=$?
echo "== done $(date) =="
exit $rc
