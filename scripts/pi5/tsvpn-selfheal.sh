#!/bin/sh
# ============================================================
#  tsvpn-selfheal.sh — rebuild this machine's VPN configuration.
#
#  Runs at every boot from tsvpn-selfheal.service, and may be run
#  by hand at any time. Idempotent and safe to re-run on either
#  role.
#
#  This is also the PROVISIONER: it applies everything in
#  scripts/pi5/README.md section 5. Configuring a new machine is
#  nothing more than writing node.json and running this.
#
#  WHY IT EXISTS ON A PI: unlike GL.iNet firmware, Debian does not
#  wipe /etc or /root on upgrade, so there is no payload to
#  restore. What it does defend against is everything else that
#  quietly undoes the setup: a reboot, a `tailscale up` typed
#  without the flags, an nftables reload, someone reinstalling
#  dnsmasq. Those are silent in exactly the same way.
#
#  Generic. All values come from /etc/tsvpn/node.json.
# ============================================================
. /etc/tsvpn/tsvpn-lib.sh
tsvpn_load || exit 1
tsvpn_check || exit 1

echo "== tsvpn self-heal: ${NODE:-$(hostname)} role=$ROLE $(date) =="
[ -n "$DEPLOYMENT" ] && echo "deployment: $DEPLOYMENT"
echo "targets   : ${TARGETS:-<none>}"
echo "uplink    : $WAN_IFACE"
if [ "$ROLE" = "remote" ]; then
	echo "exit node : $EXIT_NODE"
	echo "dns       : $DNS_UPSTREAM"
	echo "lan       : $LAN_IFACE $LAN_CIDR"
fi

# --- wait for tailscaled (boot ordering is not a guarantee) ---
i=0
while [ $i -lt 60 ]; do
	tailscale status >/dev/null 2>&1 && break
	sleep 5
	i=$((i + 1))
done
echo "tailscaled ready after $((i * 5))s"

# --- IP forwarding, now and across reboots ---
cat > /etc/sysctl.d/99-tsvpn.conf <<SYSCTL
# Installed by tsvpn-selfheal.sh. Required on both roles: a host forwards
# exit-node and subnet-route traffic, a remote forwards its LAN into the tunnel.
net.ipv4.ip_forward = 1
net.ipv6.conf.all.forwarding = 1
SYSCTL
sysctl -q -p /etc/sysctl.d/99-tsvpn.conf 2>/dev/null

if [ "$ROLE" = "host" ]; then
	# ---------------- exit-node SERVER ----------------
	# No NAT rules of our own: on Linux, tailscaled installs the SNAT for
	# exit-node egress and for advertised subnet routes itself, as long as its
	# netfilter mode is left on. Adding a second masquerade here is how you
	# break return traffic, not how you fix it.

	# DNS: this box resolves via the network it is plugged into -- it forwards
	# to whatever /etc/resolv.conf points at, which is the same resolver every
	# other device at the host site uses -- and serves those answers to the tailnet. A
	# remote site then gets exactly what a device sitting at the host site gets:
	# same resolver, same egress, nothing for a service to correlate.
	#
	# Deliberately NO no-resolv and NO server= here. That is the difference
	# between the two roles.
	if command -v dnsmasq >/dev/null 2>&1; then
		cat > /etc/dnsmasq.d/tsvpn.conf <<DNSMASQ
# Installed by tsvpn-selfheal.sh (role=host) -- do not hand-edit.
# Serve DNS to the tailnet; resolve via this network's own resolver.
interface=tailscale0
bind-dynamic
no-dhcp-interface=tailscale0
domain-needed
bogus-priv
DNSMASQ
		systemctl restart dnsmasq >/dev/null 2>&1 || service dnsmasq restart >/dev/null 2>&1
		echo "dns: serving the tailnet, forwarding to $(sed -n 's/^nameserver //p' /etc/resolv.conf | tr '\n' ' ')"
	else
		echo "WARNING: dnsmasq is not installed — remote sites will have no resolver."
		echo "         apt install dnsmasq, then re-run this."
	fi
else
	# ---------------- the REMOTE (exit-node client) ----------------
	# nftables in our own tables, so we never fight with Tailscale's rules and
	# can be flushed and rebuilt cleanly. A drop in any table is final, which is
	# what makes the kill-switch reliable regardless of what else accepts.
	if command -v nft >/dev/null 2>&1; then
		cat > /etc/tsvpn/nftables.conf <<NFT
#!/usr/sbin/nft -f
# Generated by tsvpn-selfheal.sh -- do not hand-edit; it is rewritten on boot.
# Re-apply by hand with:  nft -f /etc/tsvpn/nftables.conf

table inet tsvpn { }
flush table inet tsvpn
table inet tsvpn {
	chain forward {
		type filter hook forward priority filter + 10; policy accept;

		# clients may reach the tunnel, and get replies back
		iifname "$LAN_IFACE" oifname "tailscale0" accept
		iifname "tailscale0" oifname "$LAN_IFACE" ct state established,related accept

		# KILL-SWITCH: nothing forwarded may leave by the uplink. All client
		# traffic goes through the tunnel or nowhere. Tailscale's own encrypted
		# packets are generated locally (OUTPUT), not forwarded, so this does
		# not cut the tunnel itself. The inet family covers IPv6 too, which is
		# how a v6 leak is prevented while v4 looks perfect.
		oifname "$WAN_IFACE" drop
	}
}

table ip tsvpn_nat { }
flush table ip tsvpn_nat
table ip tsvpn_nat {
	chain postrouting {
		type nat hook postrouting priority srcnat; policy accept;

		# REQUIRED. Un-NATed client traffic entering the tunnel arrives at the
		# host sourced from this site's private range, which the host routes to
		# its own LAN and drops. Symptom if missing: this box works over the
		# tunnel, nothing behind it does.
		oifname "tailscale0" masquerade
	}
}
NFT
		nft -f /etc/tsvpn/nftables.conf && echo "nftables: masquerade + kill-switch applied" \
			|| echo "WARNING: nft refused the ruleset — clients may be unprotected"
	else
		echo "WARNING: nft not found — no NAT and NO KILL-SWITCH. apt install nftables."
	fi

	# DNS: resolve through the HOST, so the resolver egress IP and the client
	# egress IP are the same address. no-resolv stops dnsmasq falling back to
	# THIS site's resolver, which is the leak that tells a service you are on a
	# VPN. Fails closed: no tunnel means no DNS, rather than a local answer.
	if command -v dnsmasq >/dev/null 2>&1; then
		RANGE=$(python3 - "$LAN_CIDR" <<'PY'
import sys,ipaddress
i=ipaddress.ip_interface(sys.argv[1])
h=[a for a in i.network.hosts() if a != i.ip]   # never hand out our own address
if not h: sys.exit("lan_cidr leaves no usable host addresses")
if len(h) >= 200: lo,hi = h[49], h[199]         # the familiar .50-.200 on a /24
else:             lo,hi = h[len(h)//2], h[-1]   # small subnet: give away the top half
print("%s,%s"%(lo,hi))
PY
)
		[ -n "$RANGE" ] || { echo "ERROR: cannot derive a DHCP range from $LAN_CIDR"; exit 1; }
		{
		echo "# Installed by tsvpn-selfheal.sh (role=remote) -- do not hand-edit."
		echo "# Clients resolve through the host, over the tunnel. Nothing local."
		echo "interface=$LAN_IFACE"
		echo "bind-dynamic"
		echo "no-resolv"
		for s in $DNS_UPSTREAM; do echo "server=$s"; done
		echo "dhcp-range=$RANGE,12h"
		echo "dhcp-option=option:router,$LAN_ADDR"
		echo "dhcp-option=option:dns-server,$LAN_ADDR"
		echo "dhcp-authoritative"
		echo "domain-needed"
		echo "bogus-priv"
		echo "# No IPv6 handed out: if the tunnel does not carry v6, clients leak"
		echo "# over v6 while v4 looks perfect."
		echo "no-dhcpv6"
		} > /etc/dnsmasq.d/tsvpn.conf
		systemctl restart dnsmasq >/dev/null 2>&1 || service dnsmasq restart >/dev/null 2>&1
		echo "dns: clients -> $LAN_ADDR -> $DNS_UPSTREAM (the host)"
	else
		echo "WARNING: dnsmasq is not installed — clients will get no DHCP and no DNS."
		echo "         apt install dnsmasq, then re-run this."
	fi

	# No IPv6 autoconfiguration on the LAN side.
	sysctl -q -w "net.ipv6.conf.$LAN_IFACE.accept_ra=0" 2>/dev/null
fi

# --- the control-plane settings, which anything can quietly reset ---
if [ "$ROLE" = "host" ]; then
	if [ -n "$ROUTES" ]; then
		tailscale set --advertise-exit-node --advertise-routes="$ROUTES"
	else
		tailscale set --advertise-exit-node --advertise-routes=
	fi
else
	# A remote advertises NOTHING. This VPN is one-way by design: remote -> host,
	# never the reverse. Clearing explicitly matters because `tailscale set
	# --exit-node=...` leaves any existing advertisement in place, and an
	# advertised LAN sits unapproved and inert only until somebody clicks
	# approve in the console.
	tailscale set --advertise-routes= --advertise-exit-node=false \
		--exit-node="$EXIT_NODE" --exit-node-allow-lan-access --accept-routes
	sleep 2
	[ -x /etc/tsvpn/tsvpn-fix-route.sh ] && /etc/tsvpn/tsvpn-fix-route.sh
fi

echo
echo "-- verify --"
sleep 3
/etc/tsvpn/tsvpn-audit.sh
rc=$?
echo "== done $(date) =="
exit $rc
